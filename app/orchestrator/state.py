"""TypedDict state definition for LangGraph orchestrator.

Defines the core state schema shared across all nodes in the Multi-Plant
Order Allocation with Cost and Carbon orchestration pipeline.
"""

from __future__ import annotations

import uuid
from typing import Any, Dict, List, Literal, Optional, TypedDict


AnswerType = Literal[
    "allocation",
    "scenario",
    "why_order",
    "brief",
    "infeasible",
    "clarification_needed",
    "refused",
]

IntentType = Literal[
    "allocation",
    "scenario",
    "why_order",
    "diagnosis",
    "brief",
    "infeasible",
    "clarification_needed",
    "refused",
]


class WeightsDict(TypedDict, total=False):
    """Objective weights for multi-criteria optimization."""
    cost: float
    carbon: float
    lateness: Optional[float]


class ScenarioEventDict(TypedDict, total=False):
    """Scenario or capacity disturbance definition."""
    event_id: Optional[str]
    plant: str
    capacity_loss_pct: float
    from_date: Optional[str]
    to_date: Optional[str]
    description: Optional[str]


class TraceStepDict(TypedDict, total=False):
    """Trace step representation matching Annex C schema."""
    agent: str
    tool: str
    input: Optional[Dict[str, Any]]
    output: Optional[Dict[str, Any]]
    timestamp_ms: Optional[float]
    duration_ms: Optional[float]


class TokenUsageDict(TypedDict, total=False):
    """LLM token and call metrics."""
    prompt_tokens: int
    completion_tokens: int
    total_tokens: int
    llm_calls: int


class AllocationItemDict(TypedDict, total=False):
    """Single order assignment item."""
    order_id: str
    plant: str
    cost: float
    carbon_kg: float
    arrival: str
    on_time: bool


class RawSolverOutput(TypedDict, total=False):
    """Direct solver solution output."""
    status: str  # OPTIMAL, FEASIBLE, INFEASIBLE, UNBOUNDED
    allocations: List[AllocationItemDict]
    kpis: Dict[str, Any]  # total_cost, total_carbon_t, late_orders, plant_utilisation
    tradeoff: List[Dict[str, Any]]
    unallocated_orders: List[Dict[str, Any]]
    solve_time_ms: float
    solver_name: str


class ValidationResult(TypedDict, total=False):
    """Checker validator results against Annex A rules."""
    capacity_ok: bool
    eligibility_ok: bool
    delivery_ok: bool
    violations: List[str]
    warnings: List[str]
    plant_headrooms: Dict[str, float]


class DiffOutput(TypedDict, total=False):
    """Scenario comparative diff computed against base plan."""
    extra_cost: float
    extra_carbon_t: float
    late_delta: int
    orders_moved: int
    moved_order_details: List[Dict[str, Any]]
    plant_util_shifts: Dict[str, Dict[str, float]]


class RecommendationItem(TypedDict, total=False):
    """Grounding-enforced recommendation schema."""
    action: str
    rationale: str
    evidence_refs: List[str]
    confidence: Literal["HIGH", "MEDIUM", "LOW"]
    estimated_impact: str
    requires_approval: bool


class AllocationState(TypedDict, total=False):
    """TypedDict state definition for LangGraph orchestrator.

    Explicitly holds all required keys:
    - run_id: Unique trace / execution ID (e.g. 'al-62c1d8')
    - request: The raw natural language input prompt
    - weights: Objective weights dictionary (cost, carbon, lateness)
    - scenario: Optional capacity loss or scenario disturbances
    - intent: Classified user intent
    - raw_solver_output: Output directly generated by the mathematical solver
    - validation_result: Audit results verified by Annex A constraint checker
    - diff_output: Comparative metrics generated by scenario comparator
    - brief_text: Grounded executive brief text produced by writer agent
    - trace_steps: Audit trail of agent tool calls matching Annex C
    - token_usage: Token and invocation counts across all LLM steps
    - answer_type: Output response category per Section 6.2
    """
    run_id: str
    request: str
    weights: Dict[str, float]
    scenario: Optional[Dict[str, Any]]
    intent: IntentType
    raw_solver_output: Optional[Dict[str, Any]]
    validation_result: Optional[Dict[str, Any]]
    diff_output: Optional[Dict[str, Any]]
    brief_text: str
    trace_steps: List[Dict[str, Any]]
    token_usage: Dict[str, int]
    answer_type: AnswerType

    # Optional internal pipeline metadata
    summary: Optional[str]
    recommendations: Optional[List[Dict[str, Any]]]
    assumptions: Optional[List[str]]
    limitations: Optional[List[str]]
    error: Optional[str]


def create_initial_state(
    request: str,
    weights: Optional[Dict[str, float]] = None,
    scenario: Optional[Dict[str, Any]] = None,
    run_id: Optional[str] = None,
) -> AllocationState:
    """Helper to initialize an empty LangGraph allocation state."""
    rid = run_id or f"al-{uuid.uuid4().hex[:6]}"
    default_weights: Dict[str, float] = {"cost": 0.7, "carbon": 0.3}
    if weights:
        default_weights = {**default_weights, **weights}

    return AllocationState(
        run_id=rid,
        request=request,
        weights=default_weights,
        scenario=scenario,
        intent="allocation",
        raw_solver_output=None,
        validation_result=None,
        diff_output=None,
        brief_text="",
        trace_steps=[],
        token_usage={
            "prompt_tokens": 0,
            "completion_tokens": 0,
            "total_tokens": 0,
            "llm_calls": 0,
        },
        answer_type="allocation",
        summary=None,
        recommendations=[],
        assumptions=[],
        limitations=[],
        error=None,
    )
